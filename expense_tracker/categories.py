def match_category(description: str) -> str | None:
    """Return the best-matching category for a free-text description.

    Checks each keyword in KEYWORD_CATEGORY_MAP (case-insensitive, substring
    match). Returns the first matching category, or None if no match is found.

    Args:
        description: Free-text description of the expense (e.g. "Uber to airport").

    Returns:
        A category string from VALID_CATEGORIES. Falls back to
        "Miscellaneous Expenses" if no keyword matched.
    """
    lowered = description.lower()
    for category, keywords in KEYWORD_CATEGORY_MAP.items():
        for keyword in keywords:
            if keyword in lowered:
                return category
    return "Miscellaneous Expenses"
